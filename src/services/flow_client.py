    @staticmethod
    def _proxy_url_to_capsolver_fields(proxy_url: str) -> Optional[Dict[str, Any]]:
        """Parse proxy URL into capsolver task proxy fields.

        Capsolver requires separate proxyType/proxyAddress/proxyPort fields so it solves
        the captcha through the same egress IP as the Flow API request, preventing
        reCAPTCHA token-IP mismatch errors.
        """
        try:
            parsed = urlparse(proxy_url)
            scheme = (parsed.scheme or "http").lower()
            host = parsed.hostname
            port = parsed.port
            if not host or not port:
                return None
            fields: Dict[str, Any] = {
                "proxyType": scheme,
                "proxyAddress": host,
                "proxyPort": port,
            }
            if parsed.username:
                fields["proxyLogin"] = parsed.username
            if parsed.password:
                fields["proxyPassword"] = parsed.password
            return fields
        except Exception:
            return None

    async def _send_capsolver_feedback(self, solved: bool) -> None:
        """Report whether a capsolver reCAPTCHA token was accepted by the target site."""
        fingerprint = self._request_fingerprint_ctx.get()
        if not isinstance(fingerprint, dict):
            return
        ctx = fingerprint.get("capsolver_feedback")
        if not ctx:
            return
        try:
            payload = {
                "clientKey": ctx["clientKey"],
                "solved": solved,
                "task": ctx["task"],
                "result": ctx["result"],
            }
            async with AsyncSession(trust_env=False) as session:
                r = await session.post(
                    f"{ctx['base_url']}/feedbackTask",
                    json=payload,
                    timeout=10,
                )
            debug_logger.log_info(f"[capsolver] feedbackTask: solved={solved} status={r.status_code}")
        except Exception as e:
            debug_logger.log_warning(f"[capsolver] feedbackTask failed: {e}")

    def _get_remote_browser_service_config(self) -> tuple[str, str, int]:
        base_url = (config.remote_browser_base_url or "").strip().rstrip("/")
